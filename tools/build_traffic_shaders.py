"""Preserve the shared toon/ink art while adding traffic wheel vertex posing.

Emit standalone shaders so release exports do not depend on preprocessing an
included Shader resource. Rebuild after changing the shared shading or wheel pose.
"""
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SHADERS=ROOT/'assets/shaders'
pose=(SHADERS/'traffic_wheels.gdshaderinc').read_text()
for name in ['toon','ink']:
    source=(SHADERS/(name+'.gdshader')).read_text()
    marker='void vertex() {'
    assert source.count(marker)==1
    code=source.replace(marker,pose+'\n'+marker+'\n    pose_traffic_wheel(VERTEX, NORMAL, UV, UV2);')
    (SHADERS/('traffic_'+name+'.gdshader')).write_text('// Generated by tools/build_traffic_shaders.py from '+name+'.gdshader\n'+code)
print('Built standalone traffic color and ink shaders from shared art sources')
